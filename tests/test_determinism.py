"""Byte-exact determinism suite (SPEC §6): artifacts, README sync, and seeded sampling.

The goldens under ``tests/goldens/`` were generated ONCE by this module's ``--regen`` entry
point and are compared byte-for-byte (LF endings included) on every OS CI runs. Regenerate
only for a deliberate, reviewed format change::

    uv run python tests/test_determinism.py --regen

Everything feeding the goldens is fixed in this file: the items, the scripted judge outputs
(``clinevals.fakes.scripted_judge`` — no model key anywhere), the stamp (``git_sha``
``deadbeef``, ``date`` ``2026-01-01``), and the README template.
"""

import json
import sys
from collections.abc import Callable
from pathlib import Path

from langchain_core.language_models.chat_models import BaseChatModel

from clinevals import (
    EVAL_BEGIN,
    EVAL_END,
    EvalItemBase,
    EvalReport,
    GroundingVerdict,
    ItemScore,
    Rubric,
    RunStamp,
    agreement_rate,
    build_artifact,
    build_judge_input,
    invoke_judge,
    parse_grounding_verdict,
    readme_in_sync,
    score_items,
    scripted_judge,
    set_confusion,
    stratified_sample,
    sync_readme,
    verdict_metrics,
    write_artifact,
)

GOLDENS_DIR = Path(__file__).resolve().parent / "goldens"
ARTIFACT_GOLDEN = GOLDENS_DIR / "artifact.json"
README_GOLDEN = GOLDENS_DIR / "README.md"
README_COMPARISON_GOLDEN = GOLDENS_DIR / "README_comparison.md"
SAMPLE_GOLDEN = GOLDENS_DIR / "stratified_seed13.json"

COMPARISON = ("Dense-only", "dense_only_overall")
PRIMARY_LABEL = "Hybrid"

README_TEMPLATE = (
    "# Golden consumer\n"
    "\n"
    "Numbers below are generated by `clinevals.sync_readme`; never hand-edit them.\n"
    "\n"
    "## Eval results\n"
    "\n"
    f"{EVAL_BEGIN}\n"
    "| stale | table |\n"
    f"{EVAL_END}\n"
    "\n"
    "Prose after the markers is preserved verbatim.\n"
)


# --- the fixed eval ----------------------------------------------------------------------


class GoldenItem(EvalItemBase):
    gold: tuple[str, ...]
    predicted: tuple[str, ...]
    question: str = "Which care gaps are open?"
    answer: str = "See the passages."
    passages: tuple[str, ...] = ("Passage one.", "Passage two.")


_ITEMS: tuple[GoldenItem, ...] = (
    GoldenItem(item_id="dev-01", category="gap", split="dev", gold=("x", "y"), predicted=("x",)),
    GoldenItem(item_id="dev-02", category="no-gap", split="dev", gold=(), predicted=("z",)),
    # Skipped by the score_fn (returns None): must not count toward item_count.
    GoldenItem(item_id="dev-03", category="unscorable", split="dev", gold=("x",), predicted=("x",)),
    GoldenItem(
        item_id="test-01", category="gap", split="test", gold=("x", "y"), predicted=("x", "y")
    ),
    GoldenItem(item_id="test-02", category="gap", split="test", gold=("x",), predicted=("x", "w")),
    # Refusal-style item: scored on ``refused`` alone (sparse keys), never judged.
    GoldenItem(item_id="test-03", category="no-gap", split="test", gold=(), predicted=()),
)

_RUBRIC = Rubric(name="golden-grounding-v1", text="Grade each claim against the passages.\n")

# One verdict per judged item, in input order: dev-01, dev-02, test-01, test-02.
_JUDGE_SCRIPT: tuple[GroundingVerdict, ...] = (
    GroundingVerdict(
        claims_total=4,
        claims_supported=3,
        claims_unsupported=1,
        claims_contradicted=0,
        citation_valid_ratio=None,
    ),
    GroundingVerdict(
        claims_total=2,
        claims_supported=1,
        claims_unsupported=0,
        claims_contradicted=1,
        citation_valid_ratio=0.5,
    ),
    GroundingVerdict(
        claims_total=4,
        claims_supported=4,
        claims_unsupported=0,
        claims_contradicted=0,
        citation_valid_ratio=1.0,
    ),
    GroundingVerdict(
        claims_total=5,
        claims_supported=4,
        claims_unsupported=0,
        claims_contradicted=1,
        citation_valid_ratio=None,
    ),
)

_SPOT_CHECK: tuple[tuple[str, str], ...] = (
    ("supported", "supported"),
    ("unsupported", "supported"),
    ("contradicted", "contradicted"),
    ("supported", "supported"),
)

_STAMP = RunStamp(
    git_sha="deadbeef",
    date="2026-01-01",
    config_hash="cfg-0001",
    dataset_hash="ds-0001",
    models={"answer_model": "recorded-outputs", "judge_model": "scripted-judge"},
    rubric_sha256=_RUBRIC.sha256,
    judge_human_agreement=agreement_rate(_SPOT_CHECK),
    extra={"run_label": "golden"},
)

_DENSE_ONLY: dict[str, float] = {
    "citation_valid_ratio": 0.9,
    "contradiction_rate": 0.3,
    "faithfulness": 0.7,
    "hit": 0.5,
}


def _make_score_fn(judge: BaseChatModel) -> Callable[[GoldenItem], ItemScore | None]:
    def score(item: GoldenItem) -> ItemScore | None:
        if item.category == "unscorable":
            return None
        predicted, gold = set(item.predicted), set(item.gold)
        counts = set_confusion(predicted, gold)
        if not predicted and not gold:
            return ItemScore(metrics={"refused": 1.0}, counts=counts)
        payload = build_judge_input(item.question, item.answer, item.passages)
        metrics = verdict_metrics(parse_grounding_verdict(invoke_judge(judge, _RUBRIC, payload)))
        metrics["hit"] = 1.0 if predicted & gold else 0.0
        return ItemScore(metrics=metrics, counts=counts)

    return score


def build_golden_report() -> EvalReport:
    return score_items(_ITEMS, _make_score_fn(scripted_judge(_JUDGE_SCRIPT)))


def build_golden_artifact() -> dict[str, object]:
    report = build_golden_report()
    spot_check = stratified_sample(report.per_item, n=2, key=lambda r: r.category, seed=13)
    return build_artifact(
        report,
        _STAMP,
        tier="keyless",
        extra={"spot_check_item_ids": [r.item_id for r in spot_check]},
        include_per_item=True,
    )


def build_golden_comparison_artifact() -> dict[str, object]:
    """The P2 shape: a second metrics block under ``metrics`` for the two-column table."""
    artifact = build_golden_artifact()
    metrics = artifact["metrics"]
    assert isinstance(metrics, dict)
    artifact["metrics"] = {**metrics, COMPARISON[1]: dict(_DENSE_ONLY)}
    return artifact


# --- the fixed sample --------------------------------------------------------------------

SAMPLE_SEED = 13
_SAMPLE_STRATA: tuple[tuple[str, int], ...] = (("beta", 8), ("alpha", 7), ("gamma", 5))
SAMPLE_ITEMS: tuple[str, ...] = tuple(
    f"{stratum}-{i:02d}" for stratum, size in _SAMPLE_STRATA for i in range(size)
)


def _stratum(item: str) -> str:
    return item.split("-")[0]


def golden_sample() -> list[str]:
    return stratified_sample(SAMPLE_ITEMS, n=len(SAMPLE_ITEMS), key=_stratum, seed=SAMPLE_SEED)


def _sample_payload() -> dict[str, object]:
    return {
        "items": list(SAMPLE_ITEMS),
        "n": len(SAMPLE_ITEMS),
        "seed": SAMPLE_SEED,
        "sample": golden_sample(),
    }


# --- helpers -----------------------------------------------------------------------------


def _sync_template(tmp_path: Path, artifact: dict[str, object], *, comparison: bool) -> Path:
    readme = tmp_path / "README.md"
    readme.write_bytes(README_TEMPLATE.encode("utf-8"))
    if comparison:
        sync_readme(readme, artifact, comparison=COMPARISON, primary_label=PRIMARY_LABEL)
    else:
        sync_readme(readme, artifact)
    return readme


def _assert_bytes_match_golden(generated: bytes, golden_path: Path) -> None:
    assert golden_path.exists(), f"missing golden {golden_path.name}; run --regen ONCE"
    golden = golden_path.read_bytes()
    assert b"\r" not in generated, "generated bytes contain CR"
    assert b"\r" not in golden, f"{golden_path.name} was checked out with CRLF"
    # Line-wise first for a readable diff, then the exact bytes (encoding + final newline).
    assert generated.decode("utf-8").splitlines() == golden.decode("utf-8").splitlines()
    assert generated == golden


# --- artifact ----------------------------------------------------------------------------


def test_artifact_bytes_match_golden(tmp_path: Path) -> None:
    out = tmp_path / "artifact.json"
    write_artifact(out, build_golden_artifact())
    _assert_bytes_match_golden(out.read_bytes(), ARTIFACT_GOLDEN)


def test_artifact_golden_parses_back_to_the_built_payload() -> None:
    assert json.loads(ARTIFACT_GOLDEN.read_text(encoding="utf-8")) == build_golden_artifact()


def test_artifact_golden_publishes_the_test_split_only() -> None:
    report = build_golden_report()
    golden = json.loads(ARTIFACT_GOLDEN.read_text(encoding="utf-8"))
    assert golden["metrics"]["overall"] == report.test_overall
    assert golden["metrics"]["overall"] != report.overall
    assert golden["item_count"] == 5  # dev-03 skipped
    assert golden["git_sha"] == "deadbeef"
    assert golden["date"] == "2026-01-01"


def test_artifact_rewrite_is_byte_identical(tmp_path: Path) -> None:
    out = tmp_path / "artifact.json"
    write_artifact(out, build_golden_artifact())
    first = out.read_bytes()
    write_artifact(out, build_golden_artifact())
    assert out.read_bytes() == first
    assert build_golden_artifact() == build_golden_artifact()


# --- README ------------------------------------------------------------------------------


def test_readme_bytes_match_golden(tmp_path: Path) -> None:
    readme = _sync_template(tmp_path, build_golden_artifact(), comparison=False)
    _assert_bytes_match_golden(readme.read_bytes(), README_GOLDEN)


def test_readme_comparison_bytes_match_golden(tmp_path: Path) -> None:
    readme = _sync_template(tmp_path, build_golden_comparison_artifact(), comparison=True)
    _assert_bytes_match_golden(readme.read_bytes(), README_COMPARISON_GOLDEN)


def test_readme_comparison_golden_has_the_p2_header_and_placeholder() -> None:
    text = README_COMPARISON_GOLDEN.read_text(encoding="utf-8")
    assert "| Metric (test split) | Hybrid | Dense-only |" in text
    assert "| refused | 1.000 | — |" in text


def test_readme_sync_is_idempotent(tmp_path: Path) -> None:
    artifact = build_golden_artifact()
    readme = _sync_template(tmp_path, artifact, comparison=False)
    first = readme.read_bytes()
    sync_readme(readme, artifact)
    sync_readme(readme, artifact)
    assert readme.read_bytes() == first


def test_committed_goldens_are_in_sync_with_each_other() -> None:
    artifact = json.loads(ARTIFACT_GOLDEN.read_text(encoding="utf-8"))
    assert readme_in_sync(README_GOLDEN, artifact) is True
    assert (
        readme_in_sync(
            README_COMPARISON_GOLDEN,
            build_golden_comparison_artifact(),
            comparison=COMPARISON,
            primary_label=PRIMARY_LABEL,
        )
        is True
    )


def test_readme_in_sync_flips_after_a_one_digit_drift(tmp_path: Path) -> None:
    artifact = build_golden_artifact()
    readme = _sync_template(tmp_path, artifact, comparison=False)
    assert readme_in_sync(readme, artifact) is True
    text = readme.read_text(encoding="utf-8")
    assert text.count("| hit | 1.000 |") == 1
    readme.write_bytes(text.replace("| hit | 1.000 |", "| hit | 1.001 |").encode("utf-8"))
    assert readme_in_sync(readme, artifact) is False


# --- sampling ----------------------------------------------------------------------------


def test_stratified_sample_seed13_matches_golden() -> None:
    golden = json.loads(SAMPLE_GOLDEN.read_text(encoding="utf-8"))
    assert golden["items"] == list(SAMPLE_ITEMS), "golden inputs drifted; run --regen ONCE"
    assert golden["n"] == len(SAMPLE_ITEMS) == 20
    assert golden["seed"] == SAMPLE_SEED
    assert golden_sample() == golden["sample"]


def test_stratified_sample_golden_is_a_full_round_robin_permutation() -> None:
    sample = golden_sample()
    assert sorted(sample) == sorted(SAMPLE_ITEMS)
    assert [_stratum(item) for item in sample[:3]] == ["alpha", "beta", "gamma"]


def test_stratified_sample_repeated_calls_are_stable() -> None:
    assert golden_sample() == golden_sample()
    partial = stratified_sample(SAMPLE_ITEMS, n=7, key=_stratum, seed=SAMPLE_SEED)
    assert partial == golden_sample()[:7]


# --- regeneration entry point ------------------------------------------------------------


def _regenerate() -> None:
    GOLDENS_DIR.mkdir(exist_ok=True)
    write_artifact(ARTIFACT_GOLDEN, build_golden_artifact())
    README_GOLDEN.write_bytes(README_TEMPLATE.encode("utf-8"))
    sync_readme(README_GOLDEN, build_golden_artifact())
    README_COMPARISON_GOLDEN.write_bytes(README_TEMPLATE.encode("utf-8"))
    sync_readme(
        README_COMPARISON_GOLDEN,
        build_golden_comparison_artifact(),
        comparison=COMPARISON,
        primary_label=PRIMARY_LABEL,
    )
    write_artifact(SAMPLE_GOLDEN, _sample_payload())
    for path in (ARTIFACT_GOLDEN, README_GOLDEN, README_COMPARISON_GOLDEN, SAMPLE_GOLDEN):
        print(f"wrote {path.relative_to(GOLDENS_DIR.parent.parent)} ({path.stat().st_size} bytes)")


if __name__ == "__main__":
    if sys.argv[1:] != ["--regen"]:
        sys.exit("usage: uv run python tests/test_determinism.py --regen")
    _regenerate()
